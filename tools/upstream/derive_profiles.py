#!/usr/bin/env python3
"""Derive the bundled stocks that are an existing profile with different info tags.

Spektrafilm for Android, GPLv3. Film modeling powered by spektrafilm.

A derived stock carries no measured data of its own: its spectral arrays and curves are
a byte-for-byte copy of a base profile shipped from oracle c1d0e44, and only a few
``info`` tags change. The one case today is CineStill 800T, which is Kodak Vision3 500T
(5219) with its rem-jet anti-halation backing removed and sold for still cameras. The
missing backing is the stock's only physical difference, and spektrafilm already models
it: ``info.antihalation = "no"`` selects the strongest halation preset upstream defines.
The idea comes from the SpektraLab macOS port (alias profiles, GPLv3, by Hanze Qiu); this
script builds it our way, as plain profile files the engine and app read unchanged.

The script writes the derived profile next to its base and adds the base's neutral print
filter entries under the derived id, so every paper prints it exactly as it prints the
base. Re-running it is a no-op. ``--check`` fails if the committed files drift from what
it would write (wired into the JVM test DerivedProfilesTest as well).

    python3 tools/upstream/derive_profiles.py [--check]
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
ASSETS = REPO / "engine/spektra-core/src/main/assets/spektra"
PROFILES = ASSETS / "profiles"
FILTERS = ASSETS / "filters/neutral_print_filters.json"

# derived id -> (base id, info overrides, metadata note)
DERIVED = {
    "cinestill_800t": (
        "kodak_vision3_500t",
        {
            "stock": "cinestill_800t",
            "name": "CineStill 800T",
            "use": "still",
            "antihalation": "no",
            "target_print": "kodak_portra_endura",
        },
        "Derived profile: Kodak Vision3 500T (5219) with its rem-jet anti-halation backing "
        "removed, as sold for still cameras by CineStill. Every data array is copied unchanged "
        "from kodak_vision3_500t (oracle c1d0e44); only info.stock, name, use, antihalation "
        "and target_print differ. antihalation 'no' selects spektrafilm's own no-backing "
        "halation preset. Generated by tools/upstream/derive_profiles.py; do not edit by hand.",
    ),
}


def derived_profile_text(derived_id: str) -> str:
    base_id, overrides, note = DERIVED[derived_id]
    base_text = (PROFILES / f"{base_id}.json").read_text(encoding="utf-8")
    doc = json.loads(base_text)
    doc["info"].update(overrides)
    doc["metadata"]["derived_from"] = base_id
    doc["metadata"]["derivation"] = note
    # The bundled profiles are exactly json.dumps(indent=4) with no trailing newline, so
    # the derived file diffs against its base in the info block only.
    return json.dumps(doc, indent=4, ensure_ascii=False)


def filters_text() -> str:
    """neutral_print_filters.json with each derived id given its base's entry.

    Edited as text, not re-serialised, so every existing number keeps its exact digits:
    the default print path reads this file and the parity goldens depend on it.
    """
    text = FILTERS.read_text(encoding="utf-8")
    for derived_id, (base_id, _, _) in DERIVED.items():
        # Drop any previous derived entry so the result is idempotent.
        text = re.sub(
            r',\n(?P<ind>[ \t]+)"' + re.escape(derived_id) + r'": \[[^\]]*\]',
            "", text)
        entry = re.compile(
            r'(?P<ind>[ \t]+)"' + re.escape(base_id) + r'": (?P<arr>\[[^\]]*\])')

        def add(m: re.Match) -> str:
            return (m.group(0) + ",\n" + m.group("ind") + f'"{derived_id}": ' + m.group("arr"))

        text, n = entry.subn(add, text)
        if n == 0:
            raise SystemExit(f"derive_profiles: no neutral filter entries for {base_id}")
    json.loads(text)  # still valid JSON
    return text


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if committed files drift")
    args = ap.parse_args()

    outputs = {PROFILES / f"{d}.json": derived_profile_text(d) for d in DERIVED}
    outputs[FILTERS] = filters_text()
    drift = []
    for path, want in outputs.items():
        have = path.read_text(encoding="utf-8") if path.exists() else None
        if have == want:
            continue
        if args.check:
            drift.append(path.relative_to(REPO))
        else:
            path.write_text(want, encoding="utf-8")
            print(f"derive_profiles: wrote {path.relative_to(REPO)}")
    if drift:
        print("derive_profiles: out of date (run without --check and commit): "
              + ", ".join(map(str, drift)), file=sys.stderr)
        return 1
    if args.check:
        print(f"derive_profiles: OK ({len(DERIVED)} derived profile(s))")
    return 0


if __name__ == "__main__":
    sys.exit(main())
